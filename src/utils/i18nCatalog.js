/**
 * Localizes any text string based on the active language.
 * Falls back to original text if no translation is found or if lang is 'en'.
 */
export const localizeCatalogText = (text, lang = "en") => {
  if (!text || lang === "en") return text;
  const trimmed = typeof text === "string" ? text.trim() : "";
  const match = CATALOG_TRANSLATIONS[trimmed];
  if (match && match[lang]) {
    return match[lang];
  }
  return text;
};

export default localizeCatalogText;
