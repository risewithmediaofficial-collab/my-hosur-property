export const getCountries = () => LOCATION_DATA.countries;

export const getStatesByCountry = (countryId) => {
  const country = LOCATION_DATA.countries.find((c) => c.id === countryId);
  return country ? country.states : [];
};

export const getDistrictsByState = (countryId, stateId) => {
  const states = getStatesByCountry(countryId);
  const state = states.find((s) => s.id === stateId);
  return state ? state.districts : [];
};

export const getTaluksByDistrict = (countryId, stateId, districtId) => {
  const districts = getDistrictsByState(countryId, stateId);
  const district = districts.find((d) => d.id === districtId);
  return district ? district.taluks : [];
};

export const getVillagesByTaluk = (countryId, stateId, districtId, talukId) => {
  const taluks = getTaluksByDistrict(countryId, stateId, districtId);
  const taluk = taluks.find((t) => t.id === talukId);
  return taluk ? taluk.villages : [];
};

export const getAreasByVillage = (countryId, stateId, districtId, talukId, villageId) => {
  const villages = getVillagesByTaluk(countryId, stateId, districtId, talukId);
  const village = villages.find((v) => v.id === villageId);
  return village ? village.areas : [];
};
